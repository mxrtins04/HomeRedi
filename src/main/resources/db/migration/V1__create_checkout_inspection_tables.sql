CREATE TABLE units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT NOT NULL,
    spaces TEXT[] NOT NULL,
    turnover_status VARCHAR(32) NOT NULL,
    CONSTRAINT chk_units_turnover_status
        CHECK (turnover_status IN ('OCCUPIED', 'AWAITING_INSPECTION', 'INSPECTED'))
);

CREATE TABLE post_checkout_inspections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL REFERENCES units(id),
    checkout_event_id TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT chk_post_checkout_inspections_status
        CHECK (status IN ('PENDING', 'COMPLETED')),
    CONSTRAINT uq_post_checkout_inspections_unit_checkout_event
        UNIQUE (unit_id, checkout_event_id)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_checkout_inspection_id BIGINT NOT NULL
        REFERENCES post_checkout_inspections(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    CONSTRAINT chk_tasks_status
        CHECK (status IN ('PENDING', 'PASSED'))
);

CREATE INDEX idx_tasks_post_checkout_inspection_id
    ON tasks(post_checkout_inspection_id);
